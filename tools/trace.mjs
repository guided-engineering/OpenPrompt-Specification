// Generate (or with --check, verify) the requirement map of the refoundation
// plan: .guides/traceability/refoundation.requirements.md. The map is derived
// from the prompt; edit the prompt, never the map.
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const prompt = '.guides/prompts/prompt.refoundation.yaml';
const out = resolve(root, '.guides', 'traceability', 'refoundation.requirements.md');

const run = spawnSync(process.execPath, [resolve(root, 'tools', 'ops-validate', 'cli.mjs'), '--trace', prompt], { cwd: root, encoding: 'utf8' });
if (run.status !== 0) {
  process.stderr.write(run.stdout + run.stderr);
  process.exit(1);
}

const text = `# Requirement map of the refoundation plan

Generated by \`npm run trace\` from [\`${prompt}\`](../prompts/prompt.refoundation.yaml).
Do not edit: change the prompt and regenerate. \`npm run trace -- --check\` fails
when this file is out of date.

Every outcome (\`O\`), boundary (\`B\`) and section requirement of the request in
[\`.guides/product/refoundation-request.md\`](../product/refoundation-request.md)
appears here with the steps that work on it and the checks that prove it. The
requirements of sections 5 and 8 of the request belong to the prompt
\`guided-engineering.skills-repository\` in the Skills repository, which carries
its own map at \`.guides/traceability/skills-repository.requirements.md\`.

${run.stdout}`;

if (process.argv.includes('--check')) {
  let committed = '';
  try {
    committed = readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    // reported below
  }
  if (committed !== text) {
    console.error('The requirement map is out of date. Run `npm run trace` and commit the result.');
    process.exit(1);
  }
  console.log('requirement map is up to date');
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
