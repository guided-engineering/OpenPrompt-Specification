// Generate (or with --check, verify) the requirement map of the refoundation
// plan: .guides/traceability/refoundation.requirements.md. The map is derived
// from the prompt and from its run record; edit those, never the map.
//
// The first part comes from `ops-validate --trace`: requirement -> steps and
// checks. The second part joins the run record: check -> recorded result, time,
// command and evidence, and from there requirement -> shown or open. It shows
// what the record says; it proves nothing the record does not.
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const prompt = '.guides/prompts/prompt.refoundation.yaml';
const record = '.guides/operation/worklog/2026-11-13.refoundation.md';
const out = resolve(root, '.guides', 'traceability', 'refoundation.requirements.md');
const read = (rel) => readFileSync(resolve(root, rel), 'utf8').replace(/\r\n/g, '\n');

const run = spawnSync(process.execPath, [resolve(root, 'tools', 'ops-validate', 'cli.mjs'), '--trace', prompt], { cwd: root, encoding: 'utf8' });
if (run.status !== 0) {
  process.stderr.write(run.stdout + run.stderr);
  process.exit(1);
}

// ---- the run record
const definition = parse(read(prompt));
const front = /^---\n([\s\S]*?)\n---\n/.exec(read(record));
if (!front) {
  console.error(`${record} has no front matter`);
  process.exit(1);
}
const entry = parse(front[1]);
const recorded = new Map((entry.checks ?? []).map((c) => [c.id, c]));
const code = (s) => `\`${s}\``;
const cell = (s) => String(s).replace(/\|/g, '\\|');

const checkRows = definition.verification.map((v) => {
  const r = recorded.get(v.id) ?? { result: 'not-run' };
  const evidence = (r.evidence ?? []).map(code).join('<br>') || '—';
  return `| ${code(v.id)} | ${r.result} | ${r.at ?? '—'} | ${r.command ? code(cell(r.command)) : v.run ? `${code(cell(v.run))} (not recorded)` : 'observed'} | ${r.exitCode ?? '—'} | ${evidence} |`;
});

const coverage = new Map(definition.requirements.map((q) => [q.id, []]));
for (const v of definition.verification) for (const id of v.requirements ?? []) coverage.get(id)?.push(v.id);
const state = (results) => (results.includes('fail') ? 'failing' : results.every((x) => x === 'pass') ? 'shown' : 'open');
const requirementRows = [];
const counts = { shown: 0, open: 0, failing: 0 };
for (const [id, checks] of coverage) {
  const results = checks.map((c) => recorded.get(c)?.result ?? 'not-run');
  const s = state(results);
  counts[s] += 1;
  requirementRows.push(`| ${code(id)} | ${checks.map((c, i) => `${code(c)} ${results[i]}`).join(', ')} | ${s} |`);
}
const unknown = [...recorded.keys()].filter((id) => !definition.verification.some((v) => v.id === id));

const text = `# Requirement map of the refoundation plan

Generated by \`npm run trace\` from [\`${prompt}\`](../prompts/prompt.refoundation.yaml)
and its run record [\`${record}\`](../operation/worklog/2026-11-13.refoundation.md).
Do not edit: change the prompt or the run record and regenerate.
\`npm run trace -- --check\` fails when this file is out of date.

Every outcome (\`O\`), boundary (\`B\`) and section requirement of the request in
[\`.guides/product/refoundation-request.md\`](../product/refoundation-request.md)
appears here with the steps that work on it and the checks that prove it. The
requirements of sections 5 and 8 of the request belong to the prompt
\`guided-engineering.skills-repository\` in the Skills repository, which carries
its own map at \`.guides/traceability/skills-repository.requirements.md\`.

A generated map shows that every requirement has a step and a check. It cannot
show that the translation lost nothing. That question was answered by reading:
[\`refoundation.coverage-audit.md\`](./refoundation.coverage-audit.md).

${run.stdout.trimEnd()}

## Recorded results

What the run record shows for each check, and from there for each requirement.
Record: \`${entry.entryId}\`, prompt version ${entry.prompt?.version ?? 'UNKNOWN'}, status \`${entry.status}\`, last updated ${entry.date}.
This table repeats the record. A check without a command was observed by the
executor, and the record's body says how.

| Check | Result | When | Command | Exit code | Evidence |
|---|---|---|---|---|---|
${checkRows.join('\n')}

A requirement is **shown** when every check that covers it is recorded as
\`pass\`, **failing** when one of them is recorded as \`fail\`, and **open**
otherwise. ${counts.shown} of ${coverage.size} requirements are shown, ${counts.open} are open and ${counts.failing} are failing.

| Requirement | Checks and their recorded results | State |
|---|---|---|
${requirementRows.join('\n')}
${unknown.length ? `\nThe record reports checks the prompt does not define: ${unknown.map(code).join(', ')}.\n` : ''}`;

if (process.argv.includes('--check')) {
  let committed = '';
  try {
    committed = readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    // reported below
  }
  if (committed !== text) {
    console.error('The requirement map is out of date. Run `npm run trace` and commit the result.');
    process.exit(1);
  }
  console.log('requirement map is up to date');
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
